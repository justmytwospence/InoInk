#!/bin/sh
# Collects the license texts of everything InoInk redistributes and fails if one is missing.
#  - native libraries: license files are extracted from the pinned source archives
#  - Rust crates: license expressions come from `cargo metadata` and are written to doc/LICENSES.md
#  - fonts: license strings are read from each font's name table
# Run after scripts/fetch-inputs.sh. Review the diff of doc/LICENSES.md before committing.
set -eu
cd "$(dirname "$0")/.."
IN=build/inputs
OUT=build/licenses
rm -rf "$OUT" && mkdir -p "$OUT"
FAIL=0

grab() { # component archive file-in-archive...
	comp=$1; arc=$2; shift 2
	mkdir -p "$OUT/$comp"
	python3 - "$IN/$arc" "$OUT/$comp" "$@" <<'PYG' || FAIL=1
import sys, tarfile, os
arc, out, wanted = sys.argv[1], sys.argv[2], sys.argv[3:]
t = tarfile.open(arc)
members = {m.name.split("/", 1)[1] if "/" in m.name else m.name: m for m in t.getmembers() if m.isfile()}
ok = True
for w in wanted:
    m = members.get(w)
    if m is None:
        print("missing: %s in %s" % (w, os.path.basename(arc)), file=sys.stderr)
        ok = False
        continue
    open(os.path.join(out, os.path.basename(w)), "wb").write(t.extractfile(m).read())
sys.exit(0 if ok else 1)
PYG
}

grab zlib zlib-1.3.1.tar.gz LICENSE
grab bzip2 bzip2-1.0.8.tar.gz LICENSE
grab libpng libpng-1.6.53.tar.gz LICENSE
grab libjpeg jpegsrc.v9f.tar.gz README
grab openjpeg openjpeg-2.5.4.tar.gz LICENSE
grab jbig2dec jbig2dec-0.20.tar.gz COPYING
grab freetype freetype-2.14.1.tar.gz docs/FTL.TXT docs/GPLv2.TXT
grab harfbuzz harfbuzz-12.3.0.tar.gz COPYING
grab gumbo gumbo-parser-0.10.1.tar.gz COPYING
grab djvulibre djvulibre-3.5.29.tar.gz COPYING
grab mupdf mupdf-1.27.0-source.tar.gz COPYING
cp LICENSE-AGPLv3 "$OUT/LICENSE-AGPLv3"
cp LICENSE-MIT "$OUT/LICENSE-MIT"
mkdir -p "$OUT/fonts" && cp build/OFL-1.1.txt "$OUT/fonts/OFL-1.1.txt"

python3 - <<'PY'
import json, subprocess, struct, glob, os, sys
# Rust crates actually linked into the Kobo binary graph.
meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], text=True))
pkgs = {p["id"]: p for p in meta["packages"]}
rows = sorted({(p["name"], p["version"], p.get("license") or "UNSPECIFIED") for p in pkgs.values() if p["source"]})
unspecified = [r for r in rows if r[2] == "UNSPECIFIED"]

def font_license(path):
    data = open(path, "rb").read()
    try:
        n = struct.unpack(">H", data[4:6])[0]
        tables = {data[12+16*i:16+16*i]: struct.unpack(">II", data[20+16*i:28+16*i]) for i in range(n)}
        off, length = tables[b"name"]
        fmt, count, str_off = struct.unpack(">HHH", data[off:off+6])
        found = {}
        for i in range(count):
            pid, eid, lid, nid, ln, so = struct.unpack(">HHHHHH", data[off+6+12*i:off+18+12*i])
            if nid in (0, 13, 14):
                raw = data[off+str_off+so: off+str_off+so+ln]
                s = raw.decode("utf-16-be" if pid in (0, 3) else "latin-1", "ignore")
                found.setdefault(nid, s)
        return found
    except Exception as e:
        return {}

lines = ["# Licenses", "",
 "The InoInk application is licensed AGPL-3.0-or-later (see `LICENSE-AGPLv3`), as a derivative of Plato.",
 "Its own Inoreader crates, `crates/inoink` and `crates/inoink-cli`, are also available under MIT (see `LICENSE-MIT`).",
 "This file is generated by `scripts/license-audit.sh`; the texts live in `build/licenses/` and ship in every package.", "",
 "## Native libraries (built from the pinned archives in `build/inputs.lock.json`)", "",
 "| Component | License | Text |", "|---|---|---|",
 "| MuPDF 1.27.0 | AGPL-3.0-or-later | `licenses/mupdf/COPYING` |",
 "| DjVuLibre 3.5.29 | GPL-2.0-or-later | `licenses/djvulibre/COPYING` |",
 "| jbig2dec 0.20 | AGPL-3.0-or-later | `licenses/jbig2dec/COPYING` |",
 "| FreeType 2.14.1 | FreeType License (chosen) or GPL-2.0 | `licenses/freetype/FTL.TXT` |",
 "| HarfBuzz 12.3.0 | MIT | `licenses/harfbuzz/COPYING` |",
 "| Gumbo 0.10.1 | Apache-2.0 | `licenses/gumbo/COPYING` |",
 "| libpng 1.6.53 | libpng License | `licenses/libpng/LICENSE` |",
 "| libjpeg (IJG) 9f | IJG License | `licenses/libjpeg/README` |",
 "| OpenJPEG 2.5.4 | BSD-2-Clause | `licenses/openjpeg/LICENSE` |",
 "| zlib 1.3.1 | zlib | `licenses/zlib/LICENSE` |",
 "| bzip2 1.0.8 | bzip2 license | `licenses/bzip2/LICENSE` |", "",
 "The SIL Open Font License 1.1 text is in `licenses/fonts/OFL-1.1.txt`.", "",
 "The Linaro GCC 4.9.4 toolchain and its runtime are build tools; the binaries link against the",
 "device's own C library.", "",
 "## Fonts shipped in `fonts/`", "", "| File | Copyright (from the font) | License string in the font |", "|---|---|---|"]
for f in sorted(glob.glob("fonts/*")):
    info = font_license(f)
    lic = (info.get(13) or info.get(0) or "no license string in the font").replace("\n", " ").replace("|", "/")[:160]
    cp = (info.get(0) or "").replace("\n", " ").replace("|", "/")[:120]
    lines.append(f"| `{os.path.basename(f)}` | {cp} | {lic} |")
lines += ["", "## Rust crates (from `cargo metadata`, all workspace members)", "", "| Crate | Version | License |", "|---|---|---|"]
for n, v, l in rows:
    lines.append(f"| {n} | {v} | {l} |")
lines += ["", "## Not bundled", "",
 "Hyphenation patterns, dictionaries and Plato's prebuilt `bin/` and `resources/` archives are not",
 "shipped: their redistribution terms have not been audited. Hyphenation is therefore off.", ""]
open("doc/LICENSES.md", "w").write("\n".join(lines))
if unspecified:
    print("crates without a license field:", unspecified, file=sys.stderr)
PY
[ "$FAIL" = 0 ] || { echo "license audit FAILED: missing license texts" >&2; exit 1; }
echo "License texts collected in $OUT; doc/LICENSES.md updated."
